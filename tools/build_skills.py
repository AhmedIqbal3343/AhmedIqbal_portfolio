"""Build the skills slider, the skills inventory and the asset manifest from tools/skills.json.

    python3 tools/build_skills.py            # uses logos already in assets/images/skills/
    python3 tools/build_skills.py --icons DIR  # (re)copy logos from a Simple Icons folder

Outputs
  assets/images/skills/<id>.svg   logo files (Simple Icons, CC0), one per skill that has an "icon"
  assets/js/skills-data.js        data used by the slider tooltips and the evidence panel
  index.html                      regenerates the blocks between the skills:slider and skills:inventory markers
  docs/ASSET_MANIFEST.md          the asset table
"""
import json, math, re, shutil, sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / 'tools' / 'skills.json').read_text(encoding='utf-8'))
SKILL_DIR = ROOT / 'assets' / 'images' / 'skills'
SKILL_DIR.mkdir(parents=True, exist_ok=True)
DEFAULT_ICONS = Path('/usr/local/lib/python3.13/dist-packages/material/templates/.icons/simple')

icons_src = Path(sys.argv[sys.argv.index('--icons') + 1]) if '--icons' in sys.argv else (DEFAULT_ICONS if DEFAULT_ICONS.exists() else None)
P = DATA['projects']
LV = DATA['levels']
CATS = {c['id']: c for c in DATA['categories']}

# ---------------------------------------------------------------- logos
copied, missing = [], []
for s in DATA['skills']:
    if not s.get('icon'):
        continue
    dest = SKILL_DIR / f"{s['id']}.svg"
    if icons_src and (icons_src / f"{s['icon']}.svg").exists():
        shutil.copyfile(icons_src / f"{s['icon']}.svg", dest)
        copied.append(s['id'])
    elif not dest.exists():
        missing.append(s['id'])
        s['icon'] = None
if missing:
    print('WARNING: no logo file for', missing, '— they render as text nodes')


def target(s):
    """Where a click goes: the most relevant project, else official docs."""
    if s.get('used'):
        p = P[s['used'][0]]
        return p['href'], p['title'], p['href'].startswith('http')
    if s.get('docs'):
        return s['docs'], 'official documentation', True
    return None, None, False


def logo_svg(s, cls):
    """Inline <svg><use> pointing at the sprite symbol. Works from file://, any host, any origin
    (CSS mask-image needs CORS, which is why the earlier version showed blank logos)."""
    return f'<svg class="{cls}" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><use href="#sk-{s["id"]}"/></svg>'


def logo_style(s):
    return f"-webkit-mask-image:url(assets/images/skills/{s['id']}.svg);mask-image:url(assets/images/skills/{s['id']}.svg)"


# ---------------------------------------------------------------- slider HTML
def node(s, i, n):
    href, label, ext = target(s)
    dy = round(14 * math.sin(2 * math.pi * 2 * i / n), 1)
    name = s.get('short', s['name'])
    lvl = LV[s['level']]
    aria = f"{s['name']}: {lvl}. " + (f"Open {label}" if not ext or label != 'official documentation' else 'Open official documentation') + (' (opens in a new tab)' if ext else '')
    attrs = f' target="_blank" rel="noopener"' if ext else ''
    mark = (logo_svg(s, 'snode-logo') if s.get('icon')
            else f'<span class="snode-mono">{escape(s.get("mono", name))}</span>')
    style = f"--c:{s.get('color', 'currentColor')};--cd:{s.get('dark', s.get('color', 'currentColor'))};--dy:{dy}px"
    return (f'<li class="snode lv-{s["level"]}" style="{style}">'
            f'<a href="{escape(href)}"{attrs} data-skill="{s["id"]}" aria-label="{escape(aria)}">'
            f'<span class="snode-dot">{mark}<span class="snode-lv" aria-hidden="true"></span></span>'
            f'<span class="snode-name">{escape(name)}</span></a></li>')


rows = {1: [], 2: []}
for s in DATA['skills']:
    if s.get('row'):
        rows[s['row']].append(s)
row_titles = {1: 'Models, LLMs and retrieval', 2: 'Backend, web, data and delivery'}
slider = ['<!-- skills:slider:start (generated by tools/build_skills.py; edit tools/skills.json) -->']
for r, items in rows.items():
    slider.append(f'<div class="srow" data-dir="{1 if r == 1 else -1}" role="group" aria-label="{row_titles[r]}">')
    slider.append('  <div class="srow-viewport">')
    slider.append('    <ul class="srow-track">')
    slider += ['      ' + node(s, i, len(items)) for i, s in enumerate(items)]
    slider.append('    </ul>')
    slider.append('  </div>')
    slider.append('</div>')
slider.append('<!-- skills:slider:end -->')

# ---------------------------------------------------------------- inventory HTML
inv = ['<!-- skills:inventory:start (generated by tools/build_skills.py; edit tools/skills.json) -->']
for c in DATA['categories']:
    items = [s for s in DATA['skills'] if s['cat'] == c['id']]
    inv.append('<div class="skill-group" data-reveal>')
    inv.append(f'  <h3>{escape(c["name"])}</h3>')
    inv.append(f'  <p>{escape(c["blurb"])}</p>')
    inv.append('  <ul class="chips">')
    for s in items:
        logo = (f'<span class="chip-logo-wrap" style="--c:{s["color"]};--cd:{s.get("dark", s["color"])}">' + logo_svg(s, 'chip-logo') + '</span>') if s.get('icon') else ''
        inv.append(f'    <li><button class="chip" type="button" data-skill="{s["id"]}"><span class="lv lv--{s["level"]}"></span>{logo}{escape(s["name"])}</button></li>')
    inv.append('  </ul>')
    inv.append('</div>')
inv.append('<!-- skills:inventory:end -->')

sprite = ['<!-- skills:sprite:start (generated by tools/build_skills.py) -->',
          '<svg width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false">']
for s in DATA['skills']:
    if not s.get('icon'):
        continue
    svg = (SKILL_DIR / f"{s['id']}.svg").read_text(encoding='utf-8')
    paths = re.findall(r'<path[^>]*?d="([^"]+)"', svg)
    sprite.append(f'  <symbol id="sk-{s["id"]}" viewBox="0 0 24 24">' + ''.join(f'<path d="{d}"/>' for d in paths) + '</symbol>')
sprite.append('</svg>')
sprite.append('<!-- skills:sprite:end -->')

html_path = ROOT / 'index.html'
html = html_path.read_text(encoding='utf-8')
if '<!-- skills:sprite:start' not in html:
    html = html.replace('<a class="skip-link"', '<!-- skills:sprite:start -->\n<!-- skills:sprite:end -->\n\n<a class="skip-link"', 1)
for key, block in (('sprite', sprite), ('slider', slider), ('inventory', inv)):
    pat = re.compile(r'<!-- skills:' + key + r':start.*?<!-- skills:' + key + r':end -->', re.S)
    if not pat.search(html):
        sys.exit(f'markers for skills:{key} not found in index.html')
    html = pat.sub(lambda m: '\n'.join(block), html)
html_path.write_text(html, encoding='utf-8')

# ---------------------------------------------------------------- data for JS
js = {'levels': LV, 'categories': {k: v['name'] for k, v in CATS.items()}, 'projects': P,
      'skills': {s['id']: {'name': s['name'], 'cat': s['cat'], 'level': s['level'], 'used': s.get('used', []),
                           'docs': s.get('docs')} for s in DATA['skills']}}
(ROOT / 'assets' / 'js' / 'skills-data.js').write_text(
    '/* Generated by tools/build_skills.py from tools/skills.json. Do not edit by hand. */\n'
    'window.SKILLS = ' + json.dumps(js, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')

# ---------------------------------------------------------------- manifest
lines = ['# Asset manifest', '',
         'Generated by `tools/build_skills.py` for the skills slider, plus the hand-placed assets from the ZIP.', '',
         '## Skills slider logos (`assets/images/skills/`)', '',
         '| Filename | Technology or purpose | Recommended format | Suggested dimensions | Required? | Usage | Status |',
         '|---|---|---|---|---|---|---|']
for s in DATA['skills']:
    if not s.get('row'):
        continue
    if s.get('icon'):
        st = 'Added (Simple Icons, CC0); inlined as an SVG sprite and coloured in CSS'
        fn = f'`{s["id"]}.svg`'
    else:
        st = '**Missing**: shown as a text node (no logo in the local icon set)'
        fn = f'`{s["id"]}.svg`'
    lines.append(f'| {fn} | {s["name"]} logo | SVG (single path, 24×24 viewBox) | Rendered in a 34 px box | Yes | Skills slider + inventory chip | {st} |')
lines += ['', f'{len([s for s in DATA["skills"] if s.get("icon")])} logos present; text-only nodes: '
          + ', '.join(s['name'] for s in DATA['skills'] if s.get('row') and not s.get('icon')), '']
lines += ['## Other assets', '',
          '| Filename | Technology or purpose | Recommended format | Suggested dimensions | Required? | Usage | Status |',
          '|---|---|---|---|---|---|---|',
          '| `projects/site-quickjumpstart-{800,1600}.webp` | QuickJumpStart live homepage | WebP | 1600×777 + 800 w | Yes | Client-site card, agent case study | From your ZIP (converted) |',
          '| `projects/site-glanpawspets-{800,1600}.webp` | GlanPawsPets live homepage | WebP | 1600×765 + 800 w | Yes | Client-site card, agent case study | From your ZIP (converted) |',
          '| `projects/site-batteryonline-{800,1600}.webp` | BatteryOnline live homepage | WebP | 1600×768 + 800 w | Yes | Client-site card, BatteryOnline case study | From your ZIP (converted) |',
          '| `companies/dx-creativ.webp` | DX Creativ logo | WebP on white | 192×192 (source was only 200 px) | Yes | Experience timeline | From your ZIP. **A larger original would be sharper** |',
          '| `companies/akti.webp` | Arfa Kareem Technologies (AKTI) logo | WebP on white | 192×192 | Yes | Experience timeline | From your ZIP |',
          '| `companies/cognifyz.webp` | Cognifyz Technologies logo | WebP on white | 192×192 | Yes | Experience timeline | From your ZIP |',
          '| `social/{linkedin,github,credly,gmail}.png` | Profile icons | PNG, transparent | 96×96 | Yes | Contact links | From your ZIP |',
          '| `diagrams/*.svg` | System and pipeline diagrams | SVG | 1000 w desktop, 640 w phone | Yes | Spotlight cards, case studies | Generated by tools/make_diagrams.py |',
          '| `skills/openai.svg`, `skills/groq.svg`, `skills/chromadb.svg`, `skills/faiss.svg` | Logos missing from the local icon set | SVG, single colour | 24×24 viewBox | Optional | Would replace the text nodes | **You provide** (from each brand’s press kit), then add an "icon" entry in tools/skills.json |',
          '']
(ROOT / 'docs' / 'ASSET_MANIFEST.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'logos copied: {len(copied)}, slider nodes: {sum(len(v) for v in rows.values())}, inventory skills: {len(DATA["skills"])}')
